/* Фабрика сцены «человек в круге» */
function person4(id,key,title,textFn,looks,bring){
  S[id] = { t:title, safe:true,
    text:s=> (s.f['back_'+key] ? (bring.after(s)) : textFn(s)),
    ch:s=>{
      const list = looks.slice();
      list.push({ t:bring.label, if:s=> !s.f['back_'+key] && bring.cond(s), go:null, fx:s=>{ s.f['back_'+key]=true; s.f.back4=(s.f.back4||0)+1; if(bring.fx) bring.fx(s); }, note:bring.note });
      list.push({ t:bring.failLabel||'Попробовать достучаться', if:s=> !s.f['back_'+key] && !bring.cond(s), go:null, fx:s=>{ fear(s,1); }, note:bring.fail });
      list.push({ t:'Отойти к кругу', go:'c4_crew' });
      return list;
    } };
}

